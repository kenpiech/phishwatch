import { assertEquals, assertThrows } from "@std/assert";
import { parseTile } from "./tile.ts";
import { DerError, parseCert } from "./x509.ts";
import { cleanDomain } from "./score.ts";
import { fixture, tbsOf } from "./testing.ts";

const realEntries = parseTile(fixture("real-tile.bin"));

Deno.test("real tile: every certificate and precertificate parses", () => {
  for (const e of realEntries) parseCert(e.der, e.entryType === 1); // throws on any failure
});

Deno.test("real tile: 525 SAN names in total (172 certificates cross-checked with openssl)", () => {
  const names = realEntries.flatMap((e) => parseCert(e.der, e.entryType === 1).dnsNames);
  assertEquals(names.length, 525);
});

Deno.test("real tile: first entry is www.moiseevavid.ru from Let's Encrypt", () => {
  const c = parseCert(realEntries[0].der, false);
  assertEquals(c.dnsNames, ["www.moiseevavid.ru"]);
  assertEquals(c.subjectCN, "www.moiseevavid.ru");
  assertEquals(c.issuer, "Let's Encrypt");
});

Deno.test("real tile: unique domains after cleanup (lowercase, no *., no noise)", () => {
  const domains = new Set(
    realEntries.flatMap((e) => parseCert(e.der, e.entryType === 1).dnsNames)
      .map(cleanDomain)
      .filter((d): d is string => d !== null),
  );
  assertEquals(domains.size, UNIQUE_CLEAN_DOMAINS);
});
// 525 SAN names collapse to 398 once www/bare duplicates, wildcards and noise are removed.
// Pinned from this parser's output (its SANs match openssl's for all 172 full certificates).
const UNIQUE_CLEAN_DOMAINS = 398;

Deno.test("synthetic certificate: SANs and issuer as generated by openssl", () => {
  const c = parseCert(fixture("synthetic/a.der"), false);
  assertEquals(c.dnsNames, ["acmecu-login.top", "acmecu.org", "www.acmecu.org"]);
  assertEquals(c.issuer, "Phishwatch Test CA");
});

Deno.test("precertificate path: a bare TBSCertificate gives the same names", () => {
  const der = fixture("synthetic/b.der");
  assertEquals(parseCert(tbsOf(der), true).dnsNames, parseCert(der, false).dnsNames);
});

Deno.test("garbage is rejected with a DerError", () => {
  assertThrows(() => parseCert(new Uint8Array([0x30, 0x82, 0xff, 0xff, 0x00]), false), DerError);
  assertThrows(() => parseCert(new Uint8Array([0x04, 0x01, 0x00]), false), DerError);
});
